-- =========================================================
-- Supabase Schema Setup for Md. Hasanuzzaman Portfolio
-- Run this in your Supabase Dashboard -> SQL Editor -> New Query -> Run
-- =========================================================

-- 1. Create table for website dynamic content
CREATE TABLE IF NOT EXISTS public.site_content (
  id TEXT PRIMARY KEY,
  data JSONB NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.site_content ENABLE ROW LEVEL SECURITY;

-- Allow public read access so any visitor can view the portfolio
CREATE POLICY "Public can view site content"
  ON public.site_content
  FOR SELECT
  USING (true);

-- Allow insert/update with publishable API key
CREATE POLICY "Allow update site content"
  ON public.site_content
  FOR ALL
  USING (true)
  WITH CHECK (true);

-- 2. Create table for inbound contact inquiries
CREATE TABLE IF NOT EXISTS public.inbox_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  subject TEXT,
  message TEXT NOT NULL,
  read BOOLEAN DEFAULT false NOT NULL
);

-- Enable RLS on inbox
ALTER TABLE public.inbox_messages ENABLE ROW LEVEL SECURITY;

-- Allow visitors to insert new messages via contact form
CREATE POLICY "Allow public contact message insertion"
  ON public.inbox_messages
  FOR INSERT
  WITH CHECK (true);

-- Allow read, update (mark as read), and delete
CREATE POLICY "Allow management of inbox messages"
  ON public.inbox_messages
  FOR ALL
  USING (true)
  WITH CHECK (true);

